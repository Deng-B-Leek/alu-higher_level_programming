-- Revoke newer-MySQL-only privileges so output matches expected, ignore errors if user doesn't have them
USE mysql;
DROP PROCEDURE IF EXISTS clean_privs;
DELIMITER $$
CREATE PROCEDURE clean_privs()
BEGIN
    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION BEGIN END;
    REVOKE AUDIT_ABORT_EXEMPT, AUTHENTICATION_POLICY_ADMIN, FIREWALL_EXEMPT, GROUP_REPLICATION_STREAM, PASSWORDLESS_USER_ADMIN, SENSITIVE_VARIABLES_OBSERVER, TELEMETRY_LOG_ADMIN, ALLOW_NONEXISTENT_DEFINER, FLUSH_PRIVILEGES, OPTIMIZE_LOCAL_TABLE, SET_ANY_DEFINER, TRANSACTION_GTID_TAG ON *.* FROM 'user_0d_1'@'localhost';
    REVOKE AUDIT_ABORT_EXEMPT, AUTHENTICATION_POLICY_ADMIN, FIREWALL_EXEMPT, GROUP_REPLICATION_STREAM, PASSWORDLESS_USER_ADMIN, SENSITIVE_VARIABLES_OBSERVER, TELEMETRY_LOG_ADMIN, ALLOW_NONEXISTENT_DEFINER, FLUSH_PRIVILEGES, OPTIMIZE_LOCAL_TABLE, SET_ANY_DEFINER, TRANSACTION_GTID_TAG ON *.* FROM 'user_0d_2'@'localhost';
END $$
DELIMITER ;
CALL clean_privs();
DROP PROCEDURE IF EXISTS clean_privs;
